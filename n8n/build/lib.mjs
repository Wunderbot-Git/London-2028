/** IF node (v2.2) that passes items where the expression is true to output 0. */
export const ifTrue = (id, expression) => ({
  conditions: {
    options: { caseSensitive: true, leftValue: "", typeValidation: "loose", version: 2 },
    conditions: [{ id, leftValue: `={{ ${expression} }}`, rightValue: "", operator: { type: "boolean", operation: "true", singleValue: true } }],
    combinator: "and",
  },
  options: {},
});

export function workflowBuilder() {
  let x = 0;
  const nodes = [];
  const connections = {};

  function node(name, type, typeVersion, parameters, extra = {}) {
    nodes.push({ id: `n${++x}`, name, type, typeVersion, position: [0, 0], parameters, ...extra });
    return name;
  }
  function connect(from, to, output = 0) {
    connections[from] ??= { main: [] };
    while (connections[from].main.length <= output) connections[from].main.push([]);
    connections[from].main[output].push({ node: to, type: "main", index: 0 });
  }
  function chain(...names) {
    for (let i = 1; i < names.length; i++) connect(names[i - 1], names[i]);
  }
  const codeNode = (name, libs, body) => node(name, "n8n-nodes-base.code", 2, { jsCode: code(libs, body) });

  // HTTP Request that returns { statusCode, headers, body } and never throws on 4xx/5xx,
  // so Code nodes decide what an error means.
  function http(name, { method = "GET", url, body, credentials, auth, headers, query }, extra = {}) {
    const parameters = {
      method,
      url,
      ...(auth === "predefined"
        ? { authentication: "predefinedCredentialType", nodeCredentialType: Object.keys(credentials)[0] }
        : auth
          ? { authentication: "genericCredentialType", genericAuthType: Object.keys(credentials)[0] }
          : {}),
      ...(query ? { sendQuery: true, queryParameters: { parameters: query } } : {}),
      ...(headers ? { sendHeaders: true, headerParameters: { parameters: headers } } : {}),
      ...(body ? { sendBody: true, specifyBody: "json", jsonBody: body } : {}),
      options: { response: { response: { fullResponse: true, neverError: true } } },
    };
    return node(name, "n8n-nodes-base.httpRequest", 4.2, parameters, { ...(credentials ? { credentials } : {}), ...extra });
  }

  function finish(name, layout) {
    for (const n of nodes) n.position = layout[n.name] ?? [0, 600];
    return {
      name,
      nodes,
      connections,
      settings: { executionOrder: "v1", timezone: "Europe/London", saveDataErrorExecution: "all", saveDataSuccessExecution: "all" },
      pinData: {},
      meta: { templateCredsSetupCompleted: false },
    };
  }

  return { node, connect, chain, codeNode, http, finish };
}
