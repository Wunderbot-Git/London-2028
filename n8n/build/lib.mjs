// Shared pieces for building n8n workflow JSON from src/*.js.
// Code nodes cannot import modules, so the needed source files are inlined into each node.
import { readFileSync } from "node:fs";

const src = (name) =>
  readFileSync(new URL(`../src/${name}.js`, import.meta.url), "utf8")
    .replace(/^import .*;\n/gm, "")
    .replace(/^export /gm, "");

// Dependency order matters: later files use functions of earlier ones.
const lib = (...names) => names.map((n) => `// ---- src/${n}.js ----\n${src(n)}`).join("\n");

// Node bodies are written indented inside the builder functions; strip that indent.
function dedent(body) {
  const lines = body.replace(/^\n+|\s+$/g, "").split("\n");
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  return lines.map((l) => l.slice(indent)).join("\n");
}

const code = (libs, body) =>
  `// Generated by n8n/build.mjs from n8n/src – edit there, not here.\n${lib(...libs)}\n// ---- node ----\n${dedent(body)}\n`;

